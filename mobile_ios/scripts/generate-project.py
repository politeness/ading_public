#!/usr/bin/env python3
"""Generate ADing.xcodeproj.

Why generate it ourselves: the project has just one SwiftUI App and one share extension, so the file list can be built by scanning directories;
a hand-written project.pbxproj is hard to review, and every new file needs clicking in Xcode. After changing files, rerun this script:

    python3 mobile_ios/scripts/generate-project.py

Object IDs are hashed from paths, so regeneration is stable and diffs only show real changes.
"""
import hashlib
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
APP = "ADing"
SRC = os.path.join(ROOT, APP)
VERSION = "1.0.1"  # all platforms share one version: same three-part number as desktop and backend
BUNDLE_ID = "com.politeness.ading"
# "Share to ADing" extension: embedded in the App, sharing the Networking code and Chinese/English strings with the App
SHARE = "ADingShare"
SHARE_DIR = os.path.join(ROOT, SHARE)
SHARE_BUNDLE_ID = BUNDLE_ID + ".share"
DEPLOYMENT = "17.0"
REGIONS = ["zh-Hans", "en"]
# App capabilities, shared by Debug, Pre and Release. Writing development for aps-environment is Xcode's standard practice:
# archives use development signing, and exporting to App Store Connect switches to production via the distribution profile; TestFlight and App Store both use production
ENTITLEMENTS = """<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<!-- Generated by scripts/generate-project.py; change capabilities in the script -->
	<key>aps-environment</key>
	<string>development</string>
	<!-- Shared with the "Share to ADing" extension: the App Group holds the current user and server environment, the keychain group holds login tokens -->
	<key>com.apple.security.application-groups</key>
	<array>
		<string>group.com.politeness.ading</string>
	</array>
	<key>keychain-access-groups</key>
	<array>
		<string>$(AppIdentifierPrefix)com.politeness.ading.shared</string>
		<string>$(AppIdentifierPrefix)com.politeness.ading</string>
	</array>
</dict>
</plist>
"""


def oid(*parts):
    return hashlib.sha1("/".join(parts).encode()).hexdigest()[:24].upper()


def q(value):
    return value if re.fullmatch(r"[A-Za-z0-9_./]+", value) else '"' + value.replace('"', '\\"') + '"'


objects = {}


def add(key, isa, **fields):
    objects[key] = (isa, fields)
    return key


def plist(value, indent):
    pad = "\t" * indent
    if isinstance(value, dict):
        inner = "".join(f"{pad}\t{q(k)} = {plist(v, indent + 1)};\n" for k, v in value.items())
        return "{\n" + inner + pad + "}"
    if isinstance(value, list):
        inner = "".join(f"{pad}\t{plist(v, indent + 1)},\n" for v in value)
        return "(\n" + inner + pad + ")"
    return q(str(value))


# ---- Scan files -----------------------------------------------------------

sources = []  # (path relative to SRC)
variant_strings = {}  # file name -> [regions]
for dirpath, dirnames, filenames in os.walk(SRC):
    dirnames[:] = sorted(d for d in dirnames if not d.endswith((".xcassets", ".lproj")))
    rel = os.path.relpath(dirpath, SRC)
    for name in sorted(filenames):
        if name.endswith(".swift"):
            sources.append(os.path.normpath(os.path.join(rel, name)))
for region in REGIONS:
    folder = os.path.join(SRC, "Resources", f"{region}.lproj")
    for name in sorted(os.listdir(folder)):
        variant_strings.setdefault(name, []).append(region)

# ---- File references and groups -------------------------------------------

groups = {}  # relative path -> list of child node IDs


def group_children(rel):
    return groups.setdefault(rel, [])


build_sources = []
for path in sources:
    ref = add(oid("file", path), "PBXFileReference", lastKnownFileType="sourcecode.swift", path=os.path.basename(path), sourceTree="<group>")
    group_children(os.path.dirname(path)).append(ref)
    build_sources.append(add(oid("build", path), "PBXBuildFile", fileRef=ref))

assets = add(oid("file", "Resources/Assets.xcassets"), "PBXFileReference", lastKnownFileType="folder.assetcatalog", path="Assets.xcassets", sourceTree="<group>")
info = add(oid("file", "Resources/Info.plist"), "PBXFileReference", lastKnownFileType="text.plist.xml", path="Info.plist", sourceTree="<group>")
# Privacy manifest: App Store requires declaring "required reason APIs" used and data collected
privacy = add(oid("file", "Resources/PrivacyInfo.xcprivacy"), "PBXFileReference", lastKnownFileType="text.xml", path="PrivacyInfo.xcprivacy", sourceTree="<group>")
# ADing's own display version is generated at build time; it doesn't occupy the bundle version field that Apple requires to be three-part
display_version = add(oid("file", "Resources/ADingVersion.plist"), "PBXFileReference", lastKnownFileType="text.plist.xml", path="ADingVersion.plist", sourceTree="DERIVED_FILE_DIR")
# App capabilities (push, App Group, shared keychain group); contents in ENTITLEMENTS
entitlements = add(oid("file", "Resources/ADing.entitlements"), "PBXFileReference", lastKnownFileType="text.plist.entitlements", path="ADing.entitlements", sourceTree="<group>")
# Machine-specific build settings (Team ID, develop server address); real values are in Build.local.xcconfig, not in Git
servers_config = add(oid("file", "Resources/Build.xcconfig"), "PBXFileReference", lastKnownFileType="text.xcconfig", path="Build.xcconfig", sourceTree="<group>")
group_children("Resources").extend([assets, info, privacy, display_version, entitlements, servers_config])
build_resources = [add(oid("build", "Resources/Assets.xcassets"), "PBXBuildFile", fileRef=assets),
                   add(oid("build", "Resources/PrivacyInfo.xcprivacy"), "PBXBuildFile", fileRef=privacy),
                   add(oid("build", "Resources/ADingVersion.plist"), "PBXBuildFile", fileRef=display_version)]
# The same offline renderer/fonts are used by desktop and iOS; preserve the math folder.
math_assets = add(oid("file", "math"), "PBXFileReference", lastKnownFileType="folder", name="math", path="../desktop_mac/src/assets/math", sourceTree="SOURCE_ROOT")
group_children("Resources").append(math_assets)
build_resources.append(add(oid("build", "math"), "PBXBuildFile", fileRef=math_assets))
share_variants = []
for name, regions in sorted(variant_strings.items()):
    children = [
        add(oid("file", region, name), "PBXFileReference", lastKnownFileType="text.plist.strings", name=region, path=f"{region}.lproj/{name}", sourceTree="<group>")
        for region in regions
    ]
    variant = add(oid("variant", name), "PBXVariantGroup", children=children, name=name, sourceTree="<group>")
    group_children("Resources").append(variant)
    build_resources.append(add(oid("build", "variant", name), "PBXBuildFile", fileRef=variant))
    share_variants.append(variant)

product = add(oid("product"), "PBXFileReference", explicitFileType="wrapper.application", includeInIndex="0", path=f"{APP}.app", sourceTree="BUILT_PRODUCTS_DIR")


def make_group(rel):
    children = list(groups.get(rel, []))
    subdirs = sorted({p.split("/")[0] if rel == "." else p[len(rel) + 1:].split("/")[0]
                      for p in groups if p != rel and (rel == "." or p.startswith(rel + "/"))})
    for sub in subdirs:
        child_rel = sub if rel == "." else f"{rel}/{sub}"
        children.insert(0, make_group(child_rel))
    fields = {"children": children, "sourceTree": "<group>"}
    fields["path"] = APP if rel == "." else os.path.basename(rel)
    return add(oid("group", rel), "PBXGroup", **fields)


app_group = make_group(".")

# ---- Share extension files ------------------------------------------------

share_sources = sorted(name for name in os.listdir(SHARE_DIR) if name.endswith(".swift"))
share_refs = [add(oid("file", SHARE, name), "PBXFileReference", lastKnownFileType="sourcecode.swift", path=name, sourceTree="<group>")
              for name in share_sources]
share_info = add(oid("file", SHARE, "Info.plist"), "PBXFileReference", lastKnownFileType="text.plist.xml", path="Info.plist", sourceTree="<group>")
share_entitlements = add(oid("file", SHARE, f"{SHARE}.entitlements"), "PBXFileReference", lastKnownFileType="text.plist.entitlements", path=f"{SHARE}.entitlements", sourceTree="<group>")
share_privacy = add(oid("file", SHARE, "PrivacyInfo.xcprivacy"), "PBXFileReference", lastKnownFileType="text.xml", path="PrivacyInfo.xcprivacy", sourceTree="<group>")
share_group = add(oid("group", SHARE), "PBXGroup", children=[*share_refs, share_info, share_entitlements, share_privacy], path=SHARE, sourceTree="<group>")
# The extension's own code, plus the App's Networking directory (login, API, attachment upload)
share_build_sources = [add(oid("build", SHARE, name), "PBXBuildFile", fileRef=ref) for name, ref in zip(share_sources, share_refs)]
share_build_sources += [add(oid("build", SHARE, "shared", path), "PBXBuildFile", fileRef=oid("file", path))
                        for path in sources if path.startswith("Networking/")]
share_build_resources = [add(oid("build", SHARE, "PrivacyInfo.xcprivacy"), "PBXBuildFile", fileRef=share_privacy)]
share_build_resources += [add(oid("build", SHARE, "variant", ref), "PBXBuildFile", fileRef=ref) for ref in share_variants]
share_product = add(oid("product", SHARE), "PBXFileReference", explicitFileType="wrapper.app-extension", includeInIndex="0", path=f"{SHARE}.appex", sourceTree="BUILT_PRODUCTS_DIR")

products_group = add(oid("group", "Products"), "PBXGroup", children=[product, share_product], name="Products", sourceTree="<group>")
main_group = add(oid("group", "main"), "PBXGroup", children=[app_group, share_group, products_group], sourceTree="<group>")

# ---- Build phases, targets, project ---------------------------------------

phase_sources = add(oid("phase", "sources"), "PBXSourcesBuildPhase", buildActionMask="2147483647", files=build_sources, runOnlyForDeploymentPostprocessing="0")
phase_resources = add(oid("phase", "resources"), "PBXResourcesBuildPhase", buildActionMask="2147483647", files=build_resources, runOnlyForDeploymentPostprocessing="0")
phase_frameworks = add(oid("phase", "frameworks"), "PBXFrameworksBuildPhase", buildActionMask="2147483647", files=[], runOnlyForDeploymentPostprocessing="0")
# Generate ADing's own display version on every build; the output is bundled separately and doesn't change the bundle version fields Apple validates
phase_display_version = add(
    oid("phase", "display-version"),
    "PBXShellScriptBuildPhase",
    alwaysOutOfDate="1",
    buildActionMask="2147483647",
    files=[],
    inputPaths=["$(SRCROOT)/scripts/generate-display-version.sh"],
    outputPaths=["$(DERIVED_FILE_DIR)/ADingVersion.plist"],
    runOnlyForDeploymentPostprocessing="0",
    shellPath="/bin/sh",
    shellScript='/bin/sh "${SRCROOT}/scripts/generate-display-version.sh" "${SCRIPT_OUTPUT_FILE_0}"',
    showEnvVarsInLog="0",
)
share_phase_sources = add(oid("phase", SHARE, "sources"), "PBXSourcesBuildPhase", buildActionMask="2147483647", files=share_build_sources, runOnlyForDeploymentPostprocessing="0")
share_phase_resources = add(oid("phase", SHARE, "resources"), "PBXResourcesBuildPhase", buildActionMask="2147483647", files=share_build_resources, runOnlyForDeploymentPostprocessing="0")
share_phase_frameworks = add(oid("phase", SHARE, "frameworks"), "PBXFrameworksBuildPhase", buildActionMask="2147483647", files=[], runOnlyForDeploymentPostprocessing="0")
# The extension is installed into the App's PlugIns directory (dstSubfolderSpec 13)
embed_share = add(oid("build", "embed", SHARE), "PBXBuildFile", fileRef=share_product, settings={"ATTRIBUTES": ["RemoveHeadersOnCopy"]})
phase_embed = add(oid("phase", "embed"), "PBXCopyFilesBuildPhase", buildActionMask="2147483647", dstPath="", dstSubfolderSpec="13",
                  files=[embed_share], name="Embed Foundation Extensions", runOnlyForDeploymentPostprocessing="0")

common = {
    "ALWAYS_SEARCH_USER_PATHS": "NO",
    "CLANG_ENABLE_MODULES": "YES",
    "CLANG_ENABLE_OBJC_ARC": "YES",
    "ENABLE_STRICT_OBJC_MSGSEND": "YES",
    "ENABLE_USER_SCRIPT_SANDBOXING": "YES",
    "GCC_NO_COMMON_BLOCKS": "YES",
    "IPHONEOS_DEPLOYMENT_TARGET": DEPLOYMENT,
    "LOCALIZATION_PREFERS_STRING_CATALOGS": "NO",
    "SDKROOT": "iphoneos",
    "SWIFT_EMIT_LOC_STRINGS": "NO",
}
project_debug = add(oid("config", "project", "Debug"), "XCBuildConfiguration", name="Debug", buildSettings={
    **common,
    "DEBUG_INFORMATION_FORMAT": "dwarf",
    "ENABLE_TESTABILITY": "YES",
    "GCC_OPTIMIZATION_LEVEL": "0",
    "ONLY_ACTIVE_ARCH": "YES",
    "SWIFT_ACTIVE_COMPILATION_CONDITIONS": "DEBUG",
    "SWIFT_OPTIMIZATION_LEVEL": "-Onone",
})
project_release = add(oid("config", "project", "Release"), "XCBuildConfiguration", name="Release", buildSettings={
    **common,
    "DEBUG_INFORMATION_FORMAT": "dwarf-with-dsym",
    "SWIFT_COMPILATION_MODE": "wholemodule",
    "VALIDATE_PRODUCT": "YES",
})
project_pre = add(oid("config", "project", "Pre"), "XCBuildConfiguration", name="Pre", buildSettings={
    **common,
    "DEBUG_INFORMATION_FORMAT": "dwarf-with-dsym",
    "SWIFT_COMPILATION_MODE": "wholemodule",
    "VALIDATE_PRODUCT": "YES",
})
target_settings = {
    "ASSETCATALOG_COMPILER_APPICON_NAME": "AppIcon",
    "ASSETCATALOG_COMPILER_GLOBAL_ACCENT_COLOR_NAME": "AccentColor",
    "CODE_SIGN_ENTITLEMENTS": f"{APP}/Resources/ADing.entitlements",
    "CODE_SIGN_STYLE": "Automatic",
    "CURRENT_PROJECT_VERSION": "1",
    "GENERATE_INFOPLIST_FILE": "NO",
    "INFOPLIST_FILE": f"{APP}/Resources/Info.plist",
    "LD_RUNPATH_SEARCH_PATHS": "$(inherited) @executable_path/Frameworks",
    "MARKETING_VERSION": VERSION,
    "PRODUCT_BUNDLE_IDENTIFIER": BUNDLE_ID,
    "PRODUCT_NAME": APP,
    "SUPPORTED_PLATFORMS": "iphoneos iphonesimulator",
    "SUPPORTS_MACCATALYST": "NO",
    "SWIFT_VERSION": "5.0",
    "TARGETED_DEVICE_FAMILY": "1",
}
# Info.plist goes through the preprocessor: development builds define ADING_DEVELOP, LAN-related keys only go into development builds, not App Store builds
target_settings["INFOPLIST_PREPROCESS"] = "YES"
target_debug = add(oid("config", "target", "Debug"), "XCBuildConfiguration", name="Debug", baseConfigurationReference=servers_config,
                   buildSettings={**target_settings, "ADING_VERSION_CHANNEL": "develop", "INFOPLIST_PREPROCESSOR_DEFINITIONS": "ADING_DEVELOP=1"})
target_release = add(oid("config", "target", "Release"), "XCBuildConfiguration", name="Release", baseConfigurationReference=servers_config,
                     buildSettings={**target_settings, "ADING_VERSION_CHANNEL": "release"})
target_pre = add(oid("config", "target", "Pre"), "XCBuildConfiguration", name="Pre", baseConfigurationReference=servers_config,
                 buildSettings={**target_settings, "ADING_VERSION_CHANNEL": "pre", "SWIFT_ACTIVE_COMPILATION_CONDITIONS": "ADING_PRE"})
project_configs = add(oid("configs", "project"), "XCConfigurationList", buildConfigurations=[project_debug, project_pre, project_release], defaultConfigurationIsVisible="0", defaultConfigurationName="Release")
target_configs = add(oid("configs", "target"), "XCConfigurationList", buildConfigurations=[target_debug, target_pre, target_release], defaultConfigurationIsVisible="0", defaultConfigurationName="Release")

share_settings = {
    # Extensions may only use extension-safe APIs; the shared Networking code is bound by this too
    "APPLICATION_EXTENSION_API_ONLY": "YES",
    "CODE_SIGN_ENTITLEMENTS": f"{SHARE}/{SHARE}.entitlements",
    "CODE_SIGN_STYLE": "Automatic",
    "CURRENT_PROJECT_VERSION": "1",
    "GENERATE_INFOPLIST_FILE": "NO",
    "INFOPLIST_FILE": f"{SHARE}/Info.plist",
    "INFOPLIST_PREPROCESS": "YES",
    "LD_RUNPATH_SEARCH_PATHS": "$(inherited) @executable_path/Frameworks @executable_path/../../Frameworks",
    "MARKETING_VERSION": VERSION,
    "PRODUCT_BUNDLE_IDENTIFIER": SHARE_BUNDLE_ID,
    "PRODUCT_NAME": SHARE,
    "SKIP_INSTALL": "YES",
    "SUPPORTED_PLATFORMS": "iphoneos iphonesimulator",
    "SUPPORTS_MACCATALYST": "NO",
    "SWIFT_VERSION": "5.0",
    "TARGETED_DEVICE_FAMILY": "1",
}
share_debug = add(oid("config", SHARE, "Debug"), "XCBuildConfiguration", name="Debug", baseConfigurationReference=servers_config,
                  buildSettings={**share_settings, "INFOPLIST_PREPROCESSOR_DEFINITIONS": "ADING_DEVELOP=1"})
share_release = add(oid("config", SHARE, "Release"), "XCBuildConfiguration", name="Release", baseConfigurationReference=servers_config, buildSettings=share_settings)
share_pre = add(oid("config", SHARE, "Pre"), "XCBuildConfiguration", name="Pre", baseConfigurationReference=servers_config,
                buildSettings={**share_settings, "SWIFT_ACTIVE_COMPILATION_CONDITIONS": "ADING_PRE"})
share_configs = add(oid("configs", SHARE), "XCConfigurationList", buildConfigurations=[share_debug, share_pre, share_release], defaultConfigurationIsVisible="0", defaultConfigurationName="Release")
share_target = add(oid("target", SHARE), "PBXNativeTarget", buildConfigurationList=share_configs,
                   buildPhases=[share_phase_sources, share_phase_frameworks, share_phase_resources], buildRules=[], dependencies=[],
                   name=SHARE, productName=SHARE, productReference=share_product, productType="com.apple.product-type.app-extension")

# The App depends on the extension: build the extension first, then install it into the App
project_key = oid("project")
share_proxy = add(oid("proxy", SHARE), "PBXContainerItemProxy", containerPortal=project_key, proxyType="1",
                  remoteGlobalIDString=share_target, remoteInfo=SHARE)
share_dependency = add(oid("dependency", SHARE), "PBXTargetDependency", target=share_target, targetProxy=share_proxy)

mqtt_package = add(oid("package", "CocoaMQTT"), "XCRemoteSwiftPackageReference",
                   repositoryURL="https://github.com/emqx/CocoaMQTT.git",
                   requirement={"kind": "exactVersion", "version": "2.4.2"})
mqtt_product = add(oid("package-product", "CocoaMQTT"), "XCSwiftPackageProductDependency",
                   package=mqtt_package, productName="CocoaMQTT")
mqtt_build = add(oid("build", "CocoaMQTT"), "PBXBuildFile", productRef=mqtt_product)
objects[phase_frameworks][1]["files"].append(mqtt_build)

target = add(oid("target"), "PBXNativeTarget", buildConfigurationList=target_configs,
             buildPhases=[phase_sources, phase_frameworks, phase_display_version, phase_resources, phase_embed], buildRules=[], dependencies=[share_dependency],
             name=APP, productName=APP, productReference=product, packageProductDependencies=[mqtt_product], productType="com.apple.product-type.application")
project = add(project_key, "PBXProject",
              attributes={"BuildIndependentTargetsInParallel": "1", "LastSwiftUpdateCheck": "1600", "LastUpgradeCheck": "1600",
                          "TargetAttributes": {target: {"CreatedOnToolsVersion": "16.0"}, share_target: {"CreatedOnToolsVersion": "16.0"}}},
              buildConfigurationList=project_configs, compatibilityVersion="Xcode 14.0", developmentRegion="zh-Hans",
              hasScannedForEncodings="0", packageReferences=[mqtt_package], knownRegions=["Base", *REGIONS], mainGroup=main_group,
              productRefGroup=products_group, projectDirPath="", projectRoot="", targets=[target, share_target])

# ---- Output ---------------------------------------------------------------

lines = ["// !$*UTF8*$!", "{", "\tarchiveVersion = 1;", "\tclasses = {\n\t};", "\tobjectVersion = 56;", "\tobjects = {"]
by_isa = {}
for key, (isa, fields) in objects.items():
    by_isa.setdefault(isa, []).append((key, fields))
for isa in sorted(by_isa):
    lines.append(f"\n/* Begin {isa} section */")
    for key, fields in sorted(by_isa[isa]):
        body = plist({"isa": isa, **fields}, 2)
        lines.append(f"\t\t{key} = {body};")
    lines.append(f"/* End {isa} section */")
lines += ["\t};", f"\trootObject = {project};", "}", ""]

out = os.path.join(ROOT, f"{APP}.xcodeproj")
os.makedirs(out, exist_ok=True)
with open(os.path.join(out, "project.pbxproj"), "w", encoding="utf-8") as handle:
    handle.write("\n".join(lines))
with open(os.path.join(SRC, "Resources", "ADing.entitlements"), "w", encoding="utf-8") as handle:
    handle.write(ENTITLEMENTS)
print(f"{out}: {len(sources)} Swift files, {len(variant_strings)} localized resources; {SHARE}: {len(share_build_sources)} Swift files")
