    @Test
    void tagChangesRequireSessionJsonAndCustomHeader() throws Exception {
        org.mockito.Mockito.reset(userTags);
        String route = "/api/users/u_target/tags";
        String body = "{\"tag\":\"PRE_GRAY\",\"enabled\":true}";
        mockMvc.perform(post(route).contentType(MediaType.APPLICATION_JSON).header("X-Ops-Request", "user-tags").content(body))
                .andExpect(status().isUnauthorized());
        Cookie cookie = sessionCookie();
        mockMvc.perform(post(route).cookie(cookie).contentType(MediaType.APPLICATION_JSON).content(body))
                .andExpect(jsonPath("$.code").value("OPS_006"));
        mockMvc.perform(post(route).cookie(cookie).contentType(MediaType.TEXT_PLAIN).content(body))
                .andExpect(status().isUnsupportedMediaType());
        mockMvc.perform(post(route).cookie(cookie).header("X-Ops-Request", "user-tags")
                .contentType(MediaType.APPLICATION_JSON).content("{\"tag\":\"PRE_GRAY\"}"))
                .andExpect(jsonPath("$.code").value("OPS_006"));
        org.mockito.Mockito.verifyNoInteractions(userTags);
        when(userTags.change("u_target", "PRE_GRAY", true, "opsadmin")).thenReturn(List.of("PRE_GRAY"));
        mockMvc.perform(post(route).cookie(cookie).header("X-Ops-Request", "user-tags")
                .contentType(MediaType.APPLICATION_JSON).content(body))
                .andExpect(jsonPath("$.data[0]").value("PRE_GRAY"));
        verify(userTags).change("u_target", "PRE_GRAY", true, "opsadmin");
        mockMvc.perform(org.springframework.test.web.servlet.request.MockMvcRequestBuilders.options(route).cookie(cookie)
                .header("Origin", "https://untrusted.example").header("Access-Control-Request-Method", "POST")
                .header("Access-Control-Request-Headers", "X-Ops-Request,Content-Type"))
                .andExpect(header().doesNotExist("Access-Control-Allow-Origin"));
    }

