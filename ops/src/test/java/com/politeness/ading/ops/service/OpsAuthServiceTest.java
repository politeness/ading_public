package com.politeness.ading.ops.service;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.spy;
import static org.mockito.Mockito.times;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.verifyNoInteractions;
import static org.mockito.Mockito.when;

import com.politeness.ading.ops.common.BizException;
import com.politeness.ading.ops.common.OpsError;
import com.politeness.ading.ops.common.PasswordVerifier;
import com.politeness.ading.ops.config.OpsAccountGuard;
import com.politeness.ading.ops.config.OpsProperties;
import com.politeness.ading.ops.dal.OpsAccountRow;
import com.politeness.ading.ops.dal.mapper.OpsUserMapper;
import org.junit.jupiter.api.Test;
import org.springframework.mock.env.MockEnvironment;

/**
 * Login is the ops console's only public-facing entry that accepts passwords, so the order of checks is itself a security boundary.
 */
class OpsAuthServiceTest {

    /** Really generated by conductor's PasswordEncoder, plaintext Ops#Verify-2026 */
    private static final String PASSWORD = "Ops#Verify-2026";
    private static final String HASH =
            "pbkdf2$120000$EXIeMApy+mqoOqgBWeL62Q==$kPrPah4YESaeKTPNsIAqKlfk2Nb3zugOLOFjceIzMAk=";
    private static final String IP = "203.0.113.7";

    private final OpsUserMapper users = mock(OpsUserMapper.class);
    private final LoginThrottle throttle = mock(LoginThrottle.class);
    private final PasswordVerifier passwords = spy(new PasswordVerifier());
    private final VerificationGate gate = gate(1, 0L);
    private final OpsAuthService auth = service("opsadmin");

    private static VerificationGate gate(int permits, long waitMillis) {
        OpsProperties properties = new OpsProperties();
        properties.setLoginMaxConcurrentVerifications(permits);
        properties.setLoginVerifyWaitMillis(waitMillis);
        return new VerificationGate(properties);
    }

    {
        when(throttle.tryAcquire(anyString())).thenReturn(true);
    }

    private OpsAuthService service(String opsUsers) {
        OpsProperties properties = new OpsProperties();
        properties.setUsers(opsUsers);
        properties.setAuthSecret("a-secret-that-is-definitely-long-enough");
        MockEnvironment environment = new MockEnvironment();
        environment.setActiveProfiles("dev");
        OpsAccountGuard guard = new OpsAccountGuard(properties, environment);
        return new OpsAuthService(users, passwords, guard,
                new OpsTokenService(guard, properties, new tools.jackson.databind.ObjectMapper()), throttle, gate);
    }

    private OpsAccountRow account(String username, boolean agent, String status, String password) {
        OpsAccountRow row = new OpsAccountRow();
        row.setUserId("u_1");
        row.setUsername(username);
        row.setDisplayName("博爱的拇指");
        row.setIsAgent(agent);
        row.setStatus(status);
        row.setPassword(password);
        row.setTokenEpoch(2);
        return row;
    }

    private static OpsError codeOf(Runnable call) {
        return assertThrows(BizException.class, call::run).error();
    }

    @Test
    void issuesASessionForAnOpsAccountWithTheRightPassword() {
        when(users.findAccountByUsername("opsadmin")).thenReturn(account("opsadmin", false, "ACTIVE", HASH));

        OpsAuthService.LoginResult result = auth.login("opsadmin", PASSWORD, IP);

        assertNotNull(result.token());
        assertEquals("opsadmin", result.view().username());
        assertEquals("博爱的拇指", result.view().displayName());
        assertEquals("u_1", result.view().userId());
        assertNotNull(result.view().expiresAt());
        verify(throttle).recordSuccess(IP);
    }

    @Test
    void neverChecksTheRealHashOfAnAccountOutsideTheOpsList() {
        // The ops console is on the public internet; if it compared against the real hash of off-list accounts, an attacker hitting this endpoint with any username and password
        // could confirm whether a set of ADing credentials is valid, effectively a password checker for every account on the site
        when(users.findAccountByUsername("ordinary-user")).thenReturn(account("ordinary-user", false, "ACTIVE", HASH));

        assertEquals(OpsError.BAD_CREDENTIALS, codeOf(() -> auth.login("ordinary-user", PASSWORD, IP)),
                "Returns OPS_002 even with the correct password");
        assertEquals(OpsError.BAD_CREDENTIALS, codeOf(() -> auth.login("ordinary-user", "wrong-password", IP)));

        verify(passwords, never()).matches(anyString(), eq(HASH));
        verify(throttle, never()).recordSuccess(anyString());
    }

    @Test
    void outsiderAndWrongPasswordLookTheSameSoOpsAccountsCannotBeEnumerated() {
        // Off-list, on-list but not in the database, Agent, wrong password: same error code, and each runs exactly one PBKDF2 so the timing matches
        when(users.findAccountByUsername("opsadmin")).thenReturn(account("opsadmin", false, "ACTIVE", HASH));
        when(users.findAccountByUsername("teammate")).thenReturn(account("teammate", true, "ACTIVE", HASH));
        OpsAuthService twoOps = service("opsadmin,teammate,ghost");

        for (String name : java.util.List.of("ordinary-user", "ghost", "teammate", "opsadmin")) {
            org.mockito.Mockito.clearInvocations(passwords, users);
            assertEquals(OpsError.BAD_CREDENTIALS, codeOf(() -> twoOps.login(name, "wrong-password", IP)), name);
            verify(users).findAccountByUsername(name);
            verify(passwords, times(1)).matches(eq("wrong-password"), any());
        }
    }

    @Test
    void decoyHashingCostsAboutAsMuchAsARealCheck() {
        PasswordVerifier verifier = new PasswordVerifier();
        verifier.matches("warm-up", HASH);
        verifier.matches("warm-up", null);
        long real = 0;
        long decoy = 0;
        for (int i = 0; i < 3; i++) {
            long t0 = System.nanoTime();
            verifier.matches("wrong-password", HASH);
            long t1 = System.nanoTime();
            verifier.matches("wrong-password", null);
            long t2 = System.nanoTime();
            real += t1 - t0;
            decoy += t2 - t1;
        }
        double ratio = (double) decoy / real;
        assertTrue(ratio > 0.5 && ratio < 2.0, "Decoy and real hash should take the same order of time, actual ratio " + ratio);
    }

    @Test
    void rejectsAnOpsUsernameThatHasNoAccountRow() {
        when(users.findAccountByUsername("opsadmin")).thenReturn(null);

        assertEquals(OpsError.BAD_CREDENTIALS, codeOf(() -> auth.login("opsadmin", PASSWORD, IP)),
                "On the list but not in the database: return a generic error without revealing whether the account exists");
    }

    @Test
    void rejectsAnAgentAccountEvenIfItIsOnTheOpsList() {
        when(users.findAccountByUsername("opsadmin")).thenReturn(account("opsadmin", true, "ACTIVE", HASH));

        assertEquals(OpsError.BAD_CREDENTIALS, codeOf(() -> auth.login("opsadmin", PASSWORD, IP)),
                "Agents have no password and shouldn't get into the ops console");
    }

    @Test
    void rejectsADisabledAccount() {
        when(users.findAccountByUsername("opsadmin")).thenReturn(account("opsadmin", false, "DISABLED", HASH));

        assertEquals(OpsError.ACCOUNT_DISABLED, codeOf(() -> auth.login("opsadmin", PASSWORD, IP)));
        verify(throttle, never()).recordSuccess(anyString());
    }

    @Test
    void shortCircuitsWhenTheIpIsAlreadyBlocked() {
        when(throttle.tryAcquire(IP)).thenReturn(false);

        assertEquals(OpsError.TOO_MANY_TRIES, codeOf(() -> auth.login("opsadmin", PASSWORD, IP)));

        verifyNoInteractions(users);
        verify(passwords, never()).matches(any(), any());
    }

    @Test
    void aDisabledAccountOnlyShowsUpAfterTheRightPassword() {
        when(users.findAccountByUsername("opsadmin")).thenReturn(account("opsadmin", false, "DISABLED", HASH));

        assertEquals(OpsError.BAD_CREDENTIALS, codeOf(() -> auth.login("opsadmin", "wrong", IP)),
                "Must not reveal the account is disabled when the password is wrong");
    }

    @Test
    void trimsTheUsernameBeforeLookingItUpButNeverTrimsThePassword() {
        when(users.findAccountByUsername("opsadmin")).thenReturn(account("opsadmin", false, "ACTIVE", HASH));

        auth.login("  opsadmin  ", PASSWORD, IP);

        verify(users).findAccountByUsername("opsadmin");
        assertEquals(OpsError.BAD_CREDENTIALS, codeOf(() -> auth.login("opsadmin", PASSWORD + " ", IP)),
                "A trailing space makes a different password");
    }

    @Test
    void carriesTheTokenEpochSoChangingThePasswordKillsTheOpsSession() {
        when(users.findAccountByUsername("opsadmin")).thenReturn(account("opsadmin", false, "ACTIVE", HASH));

        OpsAuthService.LoginResult result = auth.login("opsadmin", PASSWORD, IP);

        OpsTokenService tokens = new OpsTokenService(
                guard(), properties(), new tools.jackson.databind.ObjectMapper());
        assertEquals(2, tokens.parse(result.token()).epoch(), "The epoch is written into the token, and the interceptor compares it with the database value");
    }

    @Test
    void nobodyCanLogInWhenTheOpsListIsEmpty() {
        OpsAuthService empty = service("");

        when(users.findAccountByUsername("opsadmin")).thenReturn(account("opsadmin", false, "ACTIVE", HASH));

        assertEquals(OpsError.BAD_CREDENTIALS, codeOf(() -> empty.login("opsadmin", PASSWORD, IP)));
        verify(passwords, never()).matches(anyString(), eq(HASH));
    }

    @Test
    void busyVerificationGateRejectsWithoutSpendingTheIpQuota() {
        when(users.findAccountByUsername("opsadmin")).thenReturn(account("opsadmin", false, "ACTIVE", HASH));
        assertTrue(gate.tryEnter(), "The test first takes the only verification slot");
        try {
            assertEquals(OpsError.LOGIN_BUSY, codeOf(() -> auth.login("opsadmin", PASSWORD, IP)));
            verify(throttle, never()).tryAcquire(anyString());
            verify(passwords, never()).matches(any(), any());
        } finally {
            gate.leave();
        }
        assertNotNull(auth.login("opsadmin", PASSWORD, IP).token(), "Login works normally once the slot is free");
    }

    @Test
    void verificationPermitIsReleasedEvenWhenLoginFails() {
        when(users.findAccountByUsername("opsadmin")).thenReturn(account("opsadmin", false, "ACTIVE", HASH));
        for (int i = 0; i < 3; i++) {
            assertEquals(OpsError.BAD_CREDENTIALS, codeOf(() -> auth.login("opsadmin", "wrong", IP)));
        }
        assertTrue(gate.tryEnter(), "A failed login must not leak the slot");
        gate.leave();
    }

    private OpsProperties properties() {
        OpsProperties properties = new OpsProperties();
        properties.setUsers("opsadmin");
        properties.setAuthSecret("a-secret-that-is-definitely-long-enough");
        return properties;
    }

    private OpsAccountGuard guard() {
        MockEnvironment environment = new MockEnvironment();
        environment.setActiveProfiles("dev");
        return new OpsAccountGuard(properties(), environment);
    }
}
