-- Persist problem feedback and user contacts. New tables only — older ops and conductor are unaffected. Back up before running.

CREATE TABLE `ops_feedback` (
  `id`                BIGINT(20)   NOT NULL AUTO_INCREMENT COMMENT 'ID, auto-increment',
  `gmt_created`       DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'Created time',
  `gmt_modified`      DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT 'Modified time',
  `report_id`         VARCHAR(100) NOT NULL COMMENT 'Report ID generated by the client, makes retries idempotent',
  `user_id`           VARCHAR(64)           DEFAULT NULL COMMENT 'Reporting account, empty for local mode',
  `terminal_id`       VARCHAR(128)          DEFAULT NULL COMMENT 'Reporting computer ID, same as terminals.fingerprint, empty for old clients',
  `status`            VARCHAR(16)  NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING pending, IGNORED ignored, ACCEPTED accepted, RESOLVED resolved',
  `description`       TEXT         NOT NULL COMMENT 'Problem description',
  `occurred_at`       DATETIME     NOT NULL COMMENT 'When the problem occurred, wall-clock time in ading.ops.zone',
  `submitted_at`      DATETIME     NOT NULL COMMENT 'Client submission time, wall-clock time in ading.ops.zone',
  `app_version`       VARCHAR(50)  NOT NULL COMMENT 'Client version',
  `channel`           VARCHAR(20)  NOT NULL COMMENT 'Release channel: develop / pre / release, derived from the version string suffix',
  `platform`          VARCHAR(30)  NOT NULL COMMENT 'Operating system',
  `arch`              VARCHAR(30)  NOT NULL COMMENT 'CPU architecture',
  `mode`              VARCHAR(30)  NOT NULL COMMENT 'Run mode: local standalone, remote online',
  `object_prefix`     VARCHAR(255) NOT NULL COMMENT 'OSS directory of this report',
  `handled_by`        VARCHAR(64)           DEFAULT NULL COMMENT 'Ops account that last changed the status, feedback-skill for the processing flow',
  `status_changed_at` DATETIME              DEFAULT NULL COMMENT 'Time of the last status change',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_report_id` (`report_id`),
  KEY `idx_status` (`status`, `id`),
  KEY `idx_feedback_user` (`user_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Problem feedback (written by conductor via the ops internal API)';

CREATE TABLE `ops_contact` (
  `id`           BIGINT(20)   NOT NULL AUTO_INCREMENT COMMENT 'ID, auto-increment',
  `gmt_created`  DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'Created time',
  `contact_id`   VARCHAR(100) NOT NULL COMMENT 'Contact ID generated by the client, makes retries idempotent',
  `user_id`      VARCHAR(64)           DEFAULT NULL COMMENT 'Submitting account, empty for local mode',
  `terminal_id`  VARCHAR(128)          DEFAULT NULL COMMENT 'Submitting computer ID, same as terminals.fingerprint, empty for old clients',
  `subject`      VARCHAR(120) NOT NULL COMMENT 'Subject',
  `content`      TEXT         NOT NULL COMMENT 'Content',
  `reply_to`     VARCHAR(200) NOT NULL DEFAULT '' COMMENT 'Reply-to contact, may be an empty string',
  `submitted_at` DATETIME     NOT NULL COMMENT 'Client submission time, wall-clock time in ading.ops.zone',
  `app_version`  VARCHAR(50)  NOT NULL COMMENT 'Client version',
  `channel`      VARCHAR(20)  NOT NULL COMMENT 'Release channel: develop / pre / release, derived from the version string suffix',
  `platform`     VARCHAR(30)  NOT NULL COMMENT 'Operating system',
  `arch`         VARCHAR(30)  NOT NULL COMMENT 'CPU architecture',
  `mode`         VARCHAR(30)  NOT NULL COMMENT 'Run mode: local standalone, remote online',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_contact_id` (`contact_id`),
  KEY `idx_contact_user` (`user_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='User contacts (written by conductor via the ops internal API)';

CREATE TABLE `ops_support_attachment` (
  `id`           BIGINT(20)   NOT NULL AUTO_INCREMENT COMMENT 'ID, auto-increment',
  `gmt_created`  DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'Created time',
  `owner_type`   VARCHAR(16)  NOT NULL COMMENT 'FEEDBACK problem feedback, CONTACT user contact',
  `owner_id`     VARCHAR(100) NOT NULL COMMENT 'report_id or contact_id',
  `kind`         VARCHAR(32)  NOT NULL COMMENT 'screenshot / image / log / log_archive / server_log / file',
  `name`         VARCHAR(200) NOT NULL COMMENT 'Original file name',
  `object_key`   VARCHAR(512) NOT NULL COMMENT 'OSS object key, the content lives only in OSS',
  `content_type` VARCHAR(100)          DEFAULT NULL COMMENT 'Content type',
  `size_bytes`   BIGINT(20)   NOT NULL DEFAULT 0 COMMENT 'Size in bytes',
  PRIMARY KEY (`id`),
  KEY `idx_owner` (`owner_type`, `owner_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Attachment index for problem feedback and user contacts';
