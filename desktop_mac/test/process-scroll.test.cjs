const {mkdtemp}=require('./tmp.cjs');
const {app,BrowserWindow}=require('electron');
const {join}=require('node:path');
const {tmpdir}=require('node:os');
const assert=require('node:assert/strict');
(async()=>{
 const output=await mkdtemp(join(tmpdir(),'ading-process-scroll-'));
 app.setPath('userData',join(output,'profile'));await app.whenReady();
 const win=new BrowserWindow({show:false,width:1220,height:820,webPreferences:{preload:join(__dirname,'ui-preload.cjs'),contextIsolation:true,sandbox:true,backgroundThrottling:false}});
 await win.loadFile(join(__dirname,'../src/index.html'));
 const run=s=>win.webContents.executeJavaScript(s);
 const wait=()=>run('new Promise(r=>setTimeout(r,300))');await wait();
 const click=selector=>run(`document.querySelector(${JSON.stringify(selector)}).click()`);
 const position=()=>run(`(()=>{const p=document.querySelector('#process-feed');return {top:p.scrollTop,bottom:p.scrollHeight-p.clientHeight-p.scrollTop}})()`);
 const append=async i=>run(`window.adingTest.emit('onStoreEvent',{type:'message',conversationId:'test-paused',message:{messageId:'process-${i}',conversationId:'test-paused',seq:${i},senderId:'test-c',type:'ASSISTANT',content:'完成',steps:['步骤 ${i} 第一行','步骤 ${i} 第二行','步骤 ${i} 第三行'],createdAt:'2026-09-05T13:00:00Z'}})`);
 for(let i=2;i<=22;i++)await append(i);
 await click('#toggle-process');await wait();
 assert.ok((await position()).bottom<2,'first open defaults to latest');
 await run(`document.querySelector('#process-feed').scrollTop=850`);await wait();
 const reading=await position();assert.ok(reading.top>100&&reading.bottom>100);
 await append(23);await wait();
 assert.ok(Math.abs((await position()).top-reading.top)<2,'incoming activity preserves middle position');
 await click('#process-panel-close');await wait();
 await append(24);await wait();
 await click('#toggle-process');await wait();
 assert.ok(Math.abs((await position()).top-reading.top)<2,`reopen restores middle position: ${JSON.stringify(await position())}, expected ${reading.top}`);
 await click('#process-agent-filters button:last-child');await wait();
 await click('#process-agent-filters button:first-child');await wait();
 assert.ok(Math.abs((await position()).top-reading.top)<2,'filter switch restores reading position');
 // Updates during the closing animation must not overwrite the saved position.
 await click('#process-panel-close');await append(26);await click('#toggle-process');
 await run('new Promise(r=>setTimeout(r,80))');await append(27);await wait();
 assert.ok(Math.abs((await position()).top-reading.top)<2,'animation and rapid reopen preserve layout position');
 await click('[data-conversation-id="test-direct"] .conversation-list-button');await wait();
 await click('[data-conversation-id="test-paused"] .conversation-list-button');await wait();
 await click('#toggle-process');await wait();
 assert.ok(Math.abs((await position()).top-reading.top)<2,'return to conversation restores its position');
 await run(`document.querySelector('#process-feed').scrollTop=document.querySelector('#process-feed').scrollHeight`);await wait();
 await append(28);await wait();assert.ok((await position()).bottom<2,'returning to latest resumes following');
 await click('#process-panel-close');await click('#toggle-process');await wait();
 assert.ok((await position()).bottom<2,'reopen at latest stays at latest');
 win.destroy();console.log('process-scroll: middle position, hidden updates, filters and latest follow passed');app.exit(0);
})().catch(e=>{console.error(e);app.exit(1);});
