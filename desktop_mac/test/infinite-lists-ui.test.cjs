const {mkdtemp}=require('./tmp.cjs');
const {app,BrowserWindow}=require('electron');
const {join}=require('node:path');const {tmpdir}=require('node:os');
const assert=require('node:assert/strict');
(async()=>{
 const output=await mkdtemp(join(tmpdir(),'ading-infinite-'));app.setPath('userData',join(output,'profile'));await app.whenReady();
 const win=new BrowserWindow({show:false,width:1220,height:820,webPreferences:{preload:join(__dirname,'ui-preload.cjs'),contextIsolation:true,sandbox:true,backgroundThrottling:false,additionalArguments:['--ading-test-infinite-lists']}});
 await win.loadFile(join(__dirname,'../src/index.html'));
 const run=s=>win.webContents.executeJavaScript(s);
 const wait=()=>run('new Promise(r=>setTimeout(r,350))');
 const capture=async name=>{if(process.env.ADING_LIST_PREVIEW_DIR)await require('node:fs/promises').writeFile(join(process.env.ADING_LIST_PREVIEW_DIR,name+'.png'),(await win.capturePage()).toPNG());};
 const count=selector=>run(`document.querySelectorAll(${JSON.stringify(selector)}).length`);
 const bottom=selector=>run(`(()=>{const e=document.querySelector(${JSON.stringify(selector)});e.scrollTop=e.scrollHeight;e.dispatchEvent(new Event('scroll'));})()`);
 await wait();
 await run(`localStorage.setItem('ading.onboarding.v2.local',JSON.stringify(['discover','permissions','support','create','share','avatar','switch','activity']))`);
 await win.loadFile(join(__dirname,'../src/index.html'));await wait();
 assert.equal(await count('#contact-list .conversation-list-item'),100);
 assert.equal(await count('#contact-list .sidebar-count'),0);await capture('conversations');
 await bottom('#contact-list .sidebar-scroll');await wait();
 assert.equal(await count('#contact-list .conversation-list-item'),200);
 assert.ok(await run(`document.querySelector('#contact-list .sidebar-scroll').scrollTop>0`));
 await bottom('#contact-list .sidebar-scroll');await wait();
 assert.equal(await count('#contact-list .conversation-list-item'),229);
 await run(`(()=>{const e=document.querySelector('#contact-list .sidebar-scroll');e.scrollTop=3000;window.__minRows=1e9;new MutationObserver(()=>{window.__minRows=Math.min(window.__minRows,document.querySelectorAll('#contact-list .conversation-list-item').length);}).observe(document.querySelector('#contact-list'),{childList:true,subtree:true});window.adingTest.bumpConversation();})()`);await wait();
 assert.equal(await count('#contact-list .conversation-list-item'),229,'a message in another conversation keeps loaded rows');
 assert.equal(await run('window.__minRows'),229,'the list is never emptied while reordering');
 assert.equal(await run(`document.querySelector('#contact-list .sidebar-scroll').scrollTop`),3000,'reordering keeps the scroll position');
 await run(`document.querySelector('[data-conversation-id="test-direct"] .conversation-list-button').click()`);await wait();
 await run(`document.querySelector('#conversation-switcher-button').click()`);await wait();
 assert.equal(await count('#conversation-switcher-menu [data-conversation-id]'),10);await capture('switcher');
 await bottom('.conversation-switcher-scroll');await wait();
 assert.equal(await count('#conversation-switcher-menu [data-conversation-id]'),20);
 assert.ok(await run(`document.querySelector('.conversation-switcher-scroll').scrollTop>0`));
 await run(`document.querySelector('#tab-contacts').click()`);await wait();
 assert.equal(await count('#contact-list .contact-list-item'),100);await capture('contacts');
 assert.equal(await run(`document.querySelector('#contact-list .sidebar-count').textContent`),'228');
 await bottom('#contact-list .sidebar-scroll');await wait();
 assert.equal(await count('#contact-list .contact-list-item'),200);
 await bottom('#contact-list .sidebar-scroll');await wait();
 assert.equal(await count('#contact-list .contact-list-item'),228);
 await run(`(()=>{const e=document.querySelector('#contact-list input');e.value='Paged 224';e.dispatchEvent(new Event('input'));})()`);await wait();
 assert.equal(await count('#contact-list .contact-list-item'),1,'search includes contacts beyond first page');
 assert.equal(await run(`document.querySelector('#contact-list .contact-list-item').dataset.userId`),'paged-contact-224');
 const requests=await run('window.adingListTest.requests()');
 assert.ok(requests.length>6);for(const r of requests)assert.ok(r.size<=(r.kind==='switcher'?10:100));
 win.destroy();console.log('infinite-lists: paging, counts, scroll position and full-index search passed');app.exit(0);
})().catch(e=>{console.error(e);app.exit(1);});
