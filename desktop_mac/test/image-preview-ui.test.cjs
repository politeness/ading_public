const { mkdtemp } = require('./tmp.cjs');
const { app, BrowserWindow, protocol } = require('electron');
const { join } = require('node:path');
const { tmpdir } = require('node:os');
const { writeFile } = require('node:fs/promises');
const assert = require('node:assert/strict');

protocol.registerSchemesAsPrivileged([{ scheme: 'ading-attachment', privileges: { standard: true, secure: true, supportFetchAPI: true } }]);
(async () => {
  const root = await mkdtemp(join(tmpdir(), 'ading-image-preview-'));
  app.setPath('userData', join(root, 'profile'));
  await app.whenReady();
  protocol.handle('ading-attachment', request => new Response(request.url.includes('f_image_2')
    ? '<svg xmlns="http://www.w3.org/2000/svg" width="800" height="1200"><rect width="800" height="1200" fill="#cfebff"/></svg>'
    : '<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="800"><rect width="1200" height="800" fill="#ffead1"/><circle cx="600" cy="400" r="250" fill="#fcba74"/></svg>', { headers: { 'Content-Type': 'image/svg+xml' } }));
  const win = new BrowserWindow({ show: false, width: 1220, height: 820, webPreferences: { preload: join(__dirname, 'ui-preload.cjs'), additionalArguments: ['--ading-test-images'], contextIsolation: true, sandbox: true, backgroundThrottling: false } });
  const run = source => win.webContents.executeJavaScript(source);
  const wait = () => run('new Promise(resolve=>setTimeout(resolve,300))');
  const click = selector => run(`document.querySelector(${JSON.stringify(selector)}).click()`);
  const open = () => run(`document.querySelector('#attachment-image-dialog').open`);
  await win.loadFile(join(__dirname, '../src/index.html'));
  await wait();
  await click('.message-attachments .attachment-image');
  await wait();
  assert.equal(await open(), true, 'chat images open in the ADing preview');
  assert.deepEqual(await run(`window.adingTest.openedAttachments()`), [], 'image preview never invokes an external editor');
  assert.equal(await run(`document.querySelector('#attachment-image-name').textContent`), 'image-one.png');
  assert.equal(await run(`document.querySelector('#attachment-image-preview').alt`), 'image-one.png');
  const geometry = await run(`(() => { const image=document.querySelector('#attachment-image-preview'), r=image.getBoundingClientRect(), thumbnail=document.querySelector('.message-attachments .attachment-image img').getBoundingClientRect(); return {loaded:image.complete && image.naturalWidth===1200, enlarged:r.width>thumbnail.width && r.height>thumbnail.height, fits:r.left>=0 && r.top>=0 && r.right<=innerWidth && r.bottom<=innerHeight}; })()`);
  assert.deepEqual(geometry, { loaded: true, enlarged: true, fits: true });
  assert.equal(await run(`document.querySelectorAll('#attachment-image-dialog input,#attachment-image-dialog textarea,#attachment-image-dialog [contenteditable=true],#attachment-image-dialog canvas').length`), 0, 'the viewer has no editing controls');
  assert.equal(await run(`document.querySelector('#attachment-image-close').getAttribute('aria-label')`), '关闭');
  assert.equal(await run(`document.querySelector('#attachment-image-save').textContent.trim()`), '', 'the download control is a pure icon');
  assert.equal(await run(`document.querySelector('#attachment-image-save svg').dataset.icon`), 'download');
  assert.equal(await run(`document.querySelector('#attachment-image-save').getAttribute('aria-label')`), '下载');
  await run(`document.querySelector('#attachment-image-save').dispatchEvent(new PointerEvent('pointerover',{bubbles:true}))`); await wait();
  assert.equal(await run(`document.querySelector('#icon-tooltip').textContent`), '下载');
  assert.equal(await run(`document.querySelector('#icon-tooltip').matches(':popover-open')`), true, 'the download tooltip works inside the modal');
  await run(`document.querySelector('#attachment-image-save').dispatchEvent(new PointerEvent('pointerout',{bubbles:true}))`);
  await click('#attachment-image-save'); await wait();
  assert.equal((await run(`window.adingTest.savedAttachments()`)).at(-1)[1], 'f_image_1', 'saving exports the currently previewed image');
  assert.equal(await open(), true, 'saving keeps the read-only preview open');
  await run(`window.adingTest.setAttachmentSaveOutcome('cancelled')`);
  await click('#attachment-image-save'); await wait();
  assert.equal(await run(`document.querySelector('#attachment-image-error').hidden`), true, 'cancelling a save is not an error');
  await run(`window.adingTest.setAttachmentSaveOutcome('error')`);
  await click('#attachment-image-save'); await wait();
  assert.match(await run(`document.querySelector('#attachment-image-error').textContent`), /下载失败：disk unavailable/);
  assert.equal(await run(`document.querySelector('#attachment-image-error').hidden`), false);
  assert.equal(await run(`document.querySelector('#attachment-image-save').disabled`), false, 'a failed save can be retried');
  const size = () => run(`(() => { const r=document.querySelector('#attachment-image-preview').getBoundingClientRect(), d=document.querySelector('#attachment-image-dialog').getBoundingClientRect(); return {w:r.width,h:r.height,inside:d.left>=0&&d.top>=0&&d.right<=innerWidth&&d.bottom<=innerHeight}; })()`);
  for (const [id, zh] of [['zoom-in', '放大'], ['zoom-out', '缩小']]) {
    assert.equal(await run(`document.querySelector('#attachment-image-${id}').getAttribute('aria-label')`), zh);
    assert.equal(await run(`document.querySelector('#attachment-image-${id}').dataset.tooltip`), zh);
    assert.equal(await run(`document.querySelector('#attachment-image-${id}').textContent.trim()`), '', 'zoom controls are pure icons');
  }
  const fitted = await size();
  await click('#attachment-image-zoom-in'); await wait();
  const larger = await size();
  assert.ok(Math.abs(larger.w / fitted.w - 1.25) < 0.01 && Math.abs(larger.h / fitted.h - 1.25) < 0.01, 'zoom in enlarges the image and keeps its proportions');
  assert.equal(larger.inside, true, 'the zoomed image scrolls inside the dialog instead of overflowing the window');
  assert.equal(await run(`(() => { const v=document.querySelector('#attachment-image-viewport'); return v.scrollWidth>v.clientWidth || v.scrollHeight>v.clientHeight; })()`), true, 'the enlarged image can be scrolled');
  await click('#attachment-image-zoom-out'); await click('#attachment-image-zoom-out'); await wait();
  const smaller = await size();
  assert.ok(Math.abs(smaller.w / fitted.w - 0.8) < 0.01, 'zoom out shrinks below the fitted size');
  for (let i = 0; i < 20; i++) await click('#attachment-image-zoom-out');
  assert.equal(await run(`document.querySelector('#attachment-image-zoom-out').disabled`), true, 'zoom out stops at the minimum');
  assert.equal(await run(`document.querySelector('#attachment-image-zoom-in').disabled`), false);
  for (let i = 0; i < 40; i++) await click('#attachment-image-zoom-in');
  assert.equal(await run(`document.querySelector('#attachment-image-zoom-in').disabled`), true, 'zoom in stops at the maximum');
  assert.equal((await size()).inside, true);
  if (process.env.ADING_TEST_SCREENSHOT) await writeFile(process.env.ADING_TEST_SCREENSHOT, (await win.webContents.capturePage()).toPNG());
  await click('#attachment-image-close'); await wait();
  assert.equal(await open(), false);

  await click('.message-attachments .attachment-image:nth-child(2)'); await wait();
  assert.equal(await run(`document.querySelector('#attachment-image-name').textContent`), 'image-two.png');
  assert.equal(await run(`document.querySelector('#attachment-image-preview').naturalHeight`), 1200);
  assert.equal(await run(`document.querySelector('#attachment-image-preview').style.width`), '', 'each image opens at the fitted size');
  assert.equal(await run(`document.querySelector('#attachment-image-zoom-in').disabled`), false);
  await run(`window.adingTest.setAttachmentSaveOutcome('saved')`);
  await click('#attachment-image-save'); await wait();
  assert.equal((await run(`window.adingTest.savedAttachments()`)).at(-1)[1], 'f_image_2', 'switching images updates the save target');
  win.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Escape' });
  win.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Escape' });
  await wait();
  assert.equal(await open(), false, 'Esc closes the preview');
  await click('.message-attachments .attachment-image'); await wait();
  await run(`(() => { const dialog=document.querySelector('#attachment-image-dialog'); for (const type of ['pointerdown','pointerup']) dialog.dispatchEvent(new PointerEvent(type,{bubbles:true,clientX:0,clientY:0})); dialog.dispatchEvent(new MouseEvent('click',{bubbles:true,clientX:0,clientY:0})); })()`);
  await wait();
  assert.equal(await open(), false, 'clicking the backdrop closes the preview');
  await click('.message-attachments .attachment-file'); await wait();
  assert.equal((await run(`window.adingTest.openedAttachments()`)).at(-1)[1], 'f_document', 'ordinary files keep their system open action');

  await click('#attach-button'); await wait();
  await click('#composer-attachments .composer-attachment-image'); await wait();
  assert.equal(await open(), true, 'an image waiting in the composer opens in the preview before it is sent');
  assert.equal(await run(`document.querySelector('#attachment-image-name').textContent`), '截图1.png');
  assert.match(await run(`document.querySelector('#attachment-image-preview').src`), /^ading-attachment:\/\/file\/_\/f_test_1\//);
  assert.equal(await run(`document.querySelectorAll('#composer-attachments .composer-attachment').length`), 1, 'previewing keeps the pending image');
  await click('#attachment-image-close'); await wait();
  await click('#composer-attachments .composer-attachment-remove'); await wait();
  assert.equal(await run(`document.querySelectorAll('#composer-attachments .composer-attachment').length`), 0, 'the remove button still removes the pending image');

  await run(`localStorage.setItem('ading.language','en')`);

  await win.loadFile(join(__dirname, '../src/index.html')); await wait();
  await click('.message-attachments .attachment-image'); await wait();
  assert.equal(await run(`document.querySelector('#attachment-image-close').getAttribute('aria-label')`), 'Close');
  assert.equal(await run(`document.querySelector('#attachment-image-close').dataset.tooltip`), 'Close');
  assert.equal(await run(`document.querySelector('#attachment-image-error').textContent`), "Couldn't load the image");
  assert.equal(await run(`document.querySelector('#attachment-image-save').textContent.trim()`), '');
  assert.equal(await run(`document.querySelector('#attachment-image-save').getAttribute('aria-label')`), 'Download');
  assert.equal(await run(`document.querySelector('#attachment-image-save').dataset.tooltip`), 'Download');
  assert.equal(await run(`document.querySelector('#attachment-image-zoom-in').dataset.tooltip`), 'Zoom in');
  assert.equal(await run(`document.querySelector('#attachment-image-zoom-out').getAttribute('aria-label')`), 'Zoom out');
  await run(`document.querySelector('#attachment-image-save').dispatchEvent(new PointerEvent('pointerover',{bubbles:true}))`); await wait();
  assert.equal(await run(`document.querySelector('#icon-tooltip').textContent`), 'Download');
  assert.equal(await run(`document.querySelector('#icon-tooltip').matches(':popover-open')`), true);
  await run(`document.querySelector('#attachment-image-save').dispatchEvent(new PointerEvent('pointerout',{bubbles:true}))`);
  await run(`window.adingTest.setAttachmentSaveOutcome('error')`);
  await click('#attachment-image-save'); await wait();
  assert.equal(await run(`document.querySelector('#attachment-image-error').textContent`), "Couldn't download the image: disk unavailable");
  win.destroy();
  console.log('image-preview UI: in-app read-only viewing, image fit, close, Escape, backdrop and English passed');
  app.exit(0);
})().catch(error => { console.error(error); app.exit(1); });
