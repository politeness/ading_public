const {app,BrowserWindow}=require('electron');
const {mkdtemp,rm,writeFile}=require('node:fs/promises');
const {join}=require('node:path');
const {tmpdir}=require('node:os');
const assert=require('node:assert/strict');
app.on('window-all-closed',()=>{});
let testRoot;
(async()=>{
 const root=await mkdtemp(join(tmpdir(),'ading-install-ui-'));
 testRoot=root;app.setPath('userData',join(root,'profile'));await app.whenReady();
 const win=new BrowserWindow({show:false,webPreferences:{preload:join(__dirname,'ui-preload.cjs'),additionalArguments:['--ading-test-install'],contextIsolation:true,sandbox:true,backgroundThrottling:false}});
 const errors=[];win.webContents.on('console-message',(_event,details)=>{if(details.level==='error')errors.push(details.message);});
 await win.loadFile(join(__dirname,'../src/index.html'));
 const run=async source=>{try{return await win.webContents.executeJavaScript(source);}catch(error){console.error({source,errors,rows:await win.webContents.executeJavaScript("document.querySelector('#agent-rows').innerHTML")});throw error;}};
 const wait=()=>run('new Promise(r=>setTimeout(r,100))');
 const until=async source=>{for(let n=0;n<50;n++){if(await run(source))return;await wait();}throw Error('Timed out: '+source);};
 const row=`Array.from(document.querySelectorAll('.agent-row')).find(row=>row.querySelector('.agent-user').textContent==='qoder-cn')`;
 const noPending=async()=>assert.equal(await run(`document.querySelector('#agent-rows').textContent.includes('待检测')`),false,'never shows 待检测');
 await wait();await run(`document.querySelector('#agents-entry').click()`);await wait();
 await until(`!document.querySelector('#agent-recheck').disabled`);
 assert.ok((await run(`${row}.textContent`)).includes('未安装 CLI'));
 assert.equal(await run(`document.querySelector('.agent-row button[aria-label="移出联系人"] svg').dataset.icon`),'remove','remove-from-contacts uses the "remove" icon, not the delete trash can');
 assert.ok(await run(`!!${row}.querySelector('button[aria-label="安装 CLI"]')`),'action is 安装 CLI');
 await run(`${row}.querySelector('button[aria-label="安装 CLI"]').click()`);await wait();
 assert.ok((await run(`${row}.textContent`)).includes('安装中'));
 const before=(await run('window.adingTest.verifiedKinds()')).filter(kind=>kind==='qoder-cn').length;
 await run('window.adingTest.finishInstall()');
 await until(`${row}.textContent.includes('检测中')`);
 await noPending();
 assert.equal((await run('window.adingTest.verifiedKinds()')).filter(kind=>kind==='qoder-cn').length,before+1,'install triggers one verification of that agent');
 await run('window.adingTest.finishVerify()');
 await until(`${row}.classList.contains('ready')`);
 await noPending();
 // Existing installed CLI: remove, decline first-time consent, then explicitly agree.
 const addRow=`document.querySelector('[data-agent-kind="qoder-cn"]')`;
 await run(`${addRow}.querySelector('button[aria-label="移出联系人"]').click()`);await wait();
 await run(`${addRow}.querySelector('button[aria-label="加为联系人"]').click()`);await wait();
 assert.equal(await run(`document.querySelector('#agent-data-dialog').open`),true);
 await run(`document.querySelector('#agent-data-cancel').click()`);await until(`${addRow}.querySelector('button[aria-label="加为联系人"]').disabled === false`);
 assert.equal(await run(`${addRow}.querySelector('button[aria-label="加为联系人"]').disabled`),false);
 await run(`${addRow}.querySelector('button[aria-label="加为联系人"]').click()`);await wait();
 await run(`document.querySelector('#agent-data-agree').click()`);await until(`${addRow}.querySelector('button[aria-label="移出联系人"]') !== null`);
 assert.equal(await run(`!!${addRow}.querySelector('button[aria-label="移出联系人"]')`),true,'agreed installed CLI becomes a contact');
 assert.deepEqual(errors,[]);
 win.destroy();
 for(const lang of ['zh-CN','en']) {
  const view=new BrowserWindow({show:false,width:1100,height:760,webPreferences:{preload:join(__dirname,'ui-preload.cjs'),additionalArguments:['--ading-test-install-progress'],contextIsolation:true,sandbox:true,backgroundThrottling:false}});
  try {
   await view.loadFile(join(__dirname,'../src/index.html'));
   const js=source=>view.webContents.executeJavaScript(source);
   await js(`localStorage.setItem('ading.language',${JSON.stringify(lang)})`);
   await view.loadFile(join(__dirname,'../src/index.html'));
   const ready=async source=>{for(let n=0;n<50;n++){if(await js(source))return;await new Promise(r=>setTimeout(r,100));}throw Error('Timed out: '+source)};
   await ready("document.querySelector('[data-agent-kind=kiro]') !== null");
   await new Promise(r=>setTimeout(r,200));
   if(!await js("document.querySelector('#agents-entry').classList.contains('active')"))await js("document.querySelector('#agents-entry').click()");
   await ready("!document.querySelector('#agent-pane').hidden");
   await ready("!document.querySelector('#agent-recheck').disabled");
   const rowOf=kind=>`document.querySelector('[data-agent-kind="${kind}"]')`;
   const original=await js(`${rowOf('kiro')}.getBoundingClientRect().height`);assert.ok(original>0,'measure visible rows');
   for(const kind of ['kiro','antigravity'])await js(`${rowOf(kind)}.querySelector('.agent-right .pri').click()`);
   const emit=async(kind,text,download)=>js(`window.adingTest.emit('onAgentLifecycleProgress',${JSON.stringify({kind,action:'install',text,download})})`);
   const text=lang==='en'?'Kiro: downloading, received 3.5 MB':'Kiro：正在下载，已接收 3.5 MB';
   await emit('kiro',text,{receivedBytes:3.5*1048576,totalBytes:50*1048576});await emit('antigravity','downloading',{receivedBytes:8.2*1048576});
   assert.equal(await js("document.querySelector('#app-toast').hidden"),true,'installation emits no floating progress toast');
   assert.match(await js(`${rowOf('kiro')}.querySelector('.agent-install-progress').textContent`),/3.5 MB/);
   assert.match(await js(`${rowOf('antigravity')}.querySelector('.agent-install-progress').textContent`),/8.2 MB/);
   assert.ok(await js(`${rowOf('kiro')}.getBoundingClientRect().height > ${original}`),'download footer is below the identity row');
   assert.match(await js(`${rowOf('kiro')}.querySelector('.agent-download-caption').textContent`),/3.5 MB \/ 50.0 MB/);
   assert.equal(await js(`${rowOf('kiro')}.querySelector('progress').value`),.07);
   assert.equal(await js(`${rowOf('antigravity')}.querySelector('progress').hasAttribute('value')`),false,'unknown size never shows an invented percent');
   assert.ok(await js(`${rowOf('kiro')}.querySelector('progress').getBoundingClientRect().top > ${rowOf('kiro')}.querySelector('.agent-id').getBoundingClientRect().bottom`),'bar is at the bottom of its own card');
   assert.equal(await js(`${rowOf('kiro')}.querySelector('.agent-signal').classList.contains('bad')`),false,'installation is not an error');
   await js("document.querySelector('#agent-close').click()");
   await ready("document.querySelector('#agent-pane').hidden");
   await emit('kiro',text.replace('3.5','12.5'),{receivedBytes:12.5*1048576,totalBytes:50*1048576});
   await new Promise(r=>setTimeout(r,200));
   if(!await js("document.querySelector('#agents-entry').classList.contains('active')"))await js("document.querySelector('#agents-entry').click()");
   await ready("!document.querySelector('#agent-pane').hidden");
   await ready(`${rowOf('kiro')}.querySelector('.agent-install-progress').textContent.includes('12.5 MB')`);
   await js(`${rowOf('antigravity')}.scrollIntoView({block:'nearest'})`);
   await js('new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))');
   for(const kind of ['kiro','antigravity']){
    assert.equal(await js(`(()=>{const e=${rowOf(kind)}.querySelector('.agent-install-progress');return e.scrollWidth>e.clientWidth})()`),false,'download amount fits without clipping');
   }
   await js("new Promise(resolve=>setTimeout(resolve,500))");
   await ready("document.querySelector('#agent-pane').checkVisibility({opacityProperty:true,visibilityProperty:true}) && getComputedStyle(document.querySelector('#agent-pane')).opacity === '1'");
   if(process.env.AGENT_INSTALL_SCREENSHOTS)await writeFile(join(process.env.AGENT_INSTALL_SCREENSHOTS,`install-inline-${lang}.png`),(await view.webContents.capturePage()).toPNG());
   assert.equal(await js(`${rowOf('kiro')}.querySelector('progress').value`),.25,'reopened panel retains numeric progress');
   await emit('kiro',lang==='en'?'Verifying app':'正在校验 App');
   assert.equal(await js(`${rowOf('kiro')}.querySelector('progress').hasAttribute('value')`),false,'verification clears stale byte progress');
   await js("window.adingTest.finishInstall('kiro')");
   await ready(`${rowOf('kiro')}.classList.contains('ready')`);
   assert.equal(await js(`${rowOf('kiro')}.querySelector('.agent-install-progress').hidden`),true,'completed progress clears');
   assert.match(await js(`${rowOf('antigravity')}.querySelector('.agent-install-progress').textContent`),/8.2 MB/,'other download retains progress');
  }finally{view.destroy();}
 }
 await rm(root,{recursive:true,force:true});
 console.log('agent-install-ui: cli-missing label, install CLI action, immediate single verification, no pending state passed');app.exit(0);
})().catch(async error=>{console.error(error);if(testRoot)await rm(testRoot,{recursive:true,force:true});app.exit(1);});
