const {app,BrowserWindow}=require('electron');
const {mkdtemp,rm}=require('node:fs/promises');
const {join}=require('node:path');
const {tmpdir}=require('node:os');
const assert=require('node:assert/strict');
app.on('window-all-closed',()=>{});
(async()=>{
 const root=await mkdtemp(join(tmpdir(),'ading-feedback-ui-'));let win;
 try{
 app.setPath('userData',join(root,'profile'));await app.whenReady();
 win=new BrowserWindow({show:false,webPreferences:{preload:join(__dirname,'ui-preload.cjs'),contextIsolation:true,sandbox:true,backgroundThrottling:false}});
 await win.loadFile(join(__dirname,'../src/index.html'));
 await win.webContents.executeJavaScript("localStorage.setItem('ading.language','en')");
 await win.loadFile(join(__dirname,'../src/index.html'));
 const js=s=>win.webContents.executeJavaScript(s);
 const until=async s=>{for(let i=0;i<60;i++){if(await js(s))return;await new Promise(r=>setTimeout(r,50));}throw Error('Timed out '+s);};
 const choose=async id=>{await js(`document.querySelector('[data-conversation-id="${id}"] .conversation-list-button').click()`);await until(`document.querySelector('[data-conversation-id="${id}"] .conversation-list-button.active') !== null`);};
 const type=async text=>js(`document.querySelector('#message-input').value=${JSON.stringify(text)};document.querySelector('#message-input').dispatchEvent(new Event('input'))`);
 const input=()=>js(`document.querySelector('#message-input').value`);
 const error=()=>js(`document.querySelector('#discovery-status').hidden ? '' : document.querySelector('#discovery-status-text').textContent`);
 const submit=async()=>{await js(`window.adingTest.deferSend();document.querySelector('#composer').requestSubmit()`);await until('window.adingTest.pendingSends()===1');};
 await until(`document.querySelector('.conversation-list-button.active') !== null`);
 await choose('test-paused');await type('A failed text');
 await js(`document.querySelector('#attach-button').click()`);
 await until(`document.querySelectorAll('#composer-attachments .composer-attachment').length > 0`);
 await submit();
 await choose('test-direct');await type('B unsent text');await js('window.adingTest.failSend()');
 await new Promise(r=>setTimeout(r,100));
 assert.equal(await error(),'','A error never appears in B');assert.equal(await input(),'B unsent text');
 await choose('test-paused');assert.match(await error(),/origin unavailable/);assert.equal(await input(),'A failed text');
 assert.ok(await js(`document.querySelectorAll('#composer-attachments .composer-attachment').length === 1`),'A attachments are restored only in A');
 await choose('test-direct');assert.equal(await input(),'B unsent text');assert.equal(await error(),'');
 await choose('test-paused');await type('A second failed text');await submit();await type('A newer draft');await js('window.adingTest.failSend()');
 await until(`document.querySelector('#discovery-status-text').textContent.includes('origin unavailable')`);
 assert.equal(await input(),'A newer draft','late failure does not overwrite newer typing');
 assert.equal(await js(`document.querySelector('.status-recover').hidden`),false);
 assert.equal(await js(`document.querySelector('.status-recover').textContent`),'Restore unsent message');
 assert.equal(await js(`document.querySelector('.status-recover').disabled`),true);
 await type('');await js(`document.querySelector('.status-recover').click()`);assert.equal(await input(),'A second failed text');
 await js(`document.querySelector('#discovery-status-close').click()`);assert.equal(await error(),'');
 await choose('test-direct');await choose('test-paused');assert.equal(await error(),'','dismissal stays scoped');
 await js('window.adingTest.deferLoad()');await choose('test-direct');
 await until('window.adingTest.pendingLoads()===1');await choose('test-paused');
 await js('window.adingTest.failLoad()');await new Promise(r=>setTimeout(r,100));
 assert.equal(await error(),'','delayed B load failure never appears in A');
 await choose('test-direct');assert.match(await error(),/load unavailable/);await choose('test-paused');
 await type('old account');await submit();await js(`window.adingTest.emit('onDataSwitching',{target:'account'});window.adingTest.failSend()`);await new Promise(r=>setTimeout(r,100));
 assert.equal(await input(),'','old account completion is discarded');assert.equal(await error(),'');
 console.log('conversation-feedback UI: scoped errors, delayed failures, separate drafts/attachments, recovery, dismissal and data-session isolation passed');
 }finally{win?.destroy();await rm(root,{recursive:true,force:true});}
 app.exit(0);
})().catch(e=>{console.error(e);app.exit(1)});
