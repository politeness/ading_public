/**
 * Generates the website landing page (index.html + icon.png).
 *
 * The landing page introduces the whole app and doesn't change per version, so releases don't run this script —
 * a release only updates release.json in the same directory, which the page reads in the browser for the latest download URL.
 * Regenerate only when the page copy changes, and deploy index.html and icon.png separately.
 *
 * Usage: node scripts/make-site.mjs [output directory]
 * Output: index.html (Chinese), en/index.html (English), sitemap.xml, robots.txt, terms.html (Terms of Service), privacy.html (Privacy Policy), icon.png, agents/*.png; the feature screenshots in shots/ are generated separately by site-shots.
 */
import { writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import { AGENTS, SITE_ORIGIN, SITE_URLS, renderSite } from "./site-template.mjs";
import { renderPrivacy, renderTerms } from "./site-legal.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = process.argv[2] ?? path.join(root, "releases", "site");

await mkdir(outDir, { recursive: true });
const indexPath = path.join(outDir, "index.html");
await writeFile(indexPath, renderSite("zh"), "utf8");
await mkdir(path.join(outDir, "en"), { recursive: true });
await writeFile(path.join(outDir, "en", "index.html"), renderSite("en"), "utf8");

// For search engine indexing: the sitemap lists all pages; nginx maps robots.txt to the domain root
const alternates = Object.entries({ "zh-CN": SITE_URLS.zh, en: SITE_URLS.en, "x-default": SITE_URLS.zh })
  .map(([lang, href]) => `    <xhtml:link rel="alternate" hreflang="${lang}" href="${href}" />`).join("\n");
const sitemapUrls = [
  `  <url>\n    <loc>${SITE_URLS.zh}</loc>\n${alternates}\n  </url>`,
  `  <url>\n    <loc>${SITE_URLS.en}</loc>\n${alternates}\n  </url>`,
  `  <url>\n    <loc>${SITE_URLS.zh}terms.html</loc>\n  </url>`,
  `  <url>\n    <loc>${SITE_URLS.zh}privacy.html</loc>\n  </url>`
];
await writeFile(path.join(outDir, "sitemap.xml"),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n${sitemapUrls.join("\n")}\n</urlset>\n`, "utf8");
await writeFile(path.join(outDir, "robots.txt"),
  `User-agent: *\nAllow: /ading/\nDisallow: /ading/ops/\nDisallow: /ading/backup/\nDisallow: /pre/\n\nSitemap: ${SITE_ORIGIN}/ading/sitemap.xml\n`, "utf8");
// Terms and privacy policy: the mobile login page links to the terms (Review Guideline 1.2); a privacy policy URL is required for App Store listing
await writeFile(path.join(outDir, "terms.html"), renderTerms(), "utf8");
await writeFile(path.join(outDir, "privacy.html"), renderPrivacy(), "utf8");
// The page header shows the app icon. The original is 1024px / 1.2MB but only 64px on the page; 256px is enough for Retina
execFileSync("/usr/bin/sips", ["-Z", "256", path.join(root, "build", "icon.png"), "--out", path.join(outDir, "icon.png")], { stdio: "ignore" });

await mkdir(path.join(outDir, "agents"), { recursive: true });
// Vendor icons vary in format; normalize them into same-size white rounded icons for the page (the originals used in the app are untouched)
for (const agent of AGENTS) {
  execFileSync("/usr/bin/python3", [
    path.join(root, "scripts", "site-agent-icon.py"),
    path.join(root, "src", "assets", "agents", agent.file),
    path.join(outDir, "agents", agent.file)
  ], { stdio: "inherit" });
}

console.log(`SITE_PATH=${indexPath}`);
console.log("SITE_NOTE=Feature screenshots are in shots/, generated by node scripts/site-shots/run.mjs; upload the whole directory when deploying");
