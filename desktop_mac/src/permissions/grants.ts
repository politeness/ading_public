import { createHash } from "node:crypto";
import { tm } from "../i18n";
import { mkdir, readFile, rename, writeFile } from "node:fs/promises";
import path from "node:path";
import type { ToolPermissionRequest } from "../agents/types";

type Grants = Record<string, string[]>;
const canonical = (value: unknown): unknown => Array.isArray(value) ? value.map(canonical) :
  value && typeof value === "object" ? Object.fromEntries(Object.entries(value).sort(([a],[b])=>a.localeCompare(b)).map(([k,v])=>[k,canonical(v)])) : value;

/** Remembers only task/Agent/tool/parameter combinations the user actually chose; doesn't accept authorization rules generated by the model. */
export class PermissionGrants {
  private queue: Promise<unknown> = Promise.resolve();
  private epoch = new Map<string, number>();
  constructor(private file?: string) {}
  private data: Grants = {};
  private loaded = false;
  private async serial<T>(fn: () => Promise<T>): Promise<T> {
    const next = this.queue.then(fn,fn); this.queue=next.catch(()=>undefined); return next;
  }
  private async load(): Promise<void> {
    if(this.loaded) return;
    if(this.file) {
      try {
        const data=JSON.parse(await readFile(this.file,"utf8"));
        if(!data || Array.isArray(data) || typeof data!=="object" || !Object.values(data).every(v=>Array.isArray(v)&&v.every(s=>typeof s==="string"))) throw Error(tm("main.permission.grantsInvalid"));
        this.data=data;
      } catch(error) { if((error as NodeJS.ErrnoException).code!=="ENOENT") throw error; }
    }
    this.loaded=true;
  }
  private async save(data: Grants): Promise<void> {
    if(!this.file) return;
    await mkdir(path.dirname(this.file),{recursive:true});
    const tmp=this.file+".tmp";await writeFile(tmp,JSON.stringify(data,null,2),{mode:0o600});await rename(tmp,this.file);
  }
  revision(conversationId:string): number {return this.epoch.get(conversationId)??0;}
  key(conversation:Conversation,agent:UserRef,request:ToolPermissionRequest): string {
    return createHash("sha256").update(JSON.stringify(canonical([conversation.workspaceId,conversation.workspacePath??"",request.workspacePath??"",agent.userId,agent.localUuid,agent.kind,request.toolName,request.input]))).digest("hex");
  }
  has(conversationId:string,key:string): Promise<boolean> {return this.serial(async()=>{await this.load();return this.data[conversationId]?.includes(key)??false;});}
  grant(conversationId:string,key:string,revision:number): Promise<void> {return this.serial(async()=>{
    await this.load();if(this.revision(conversationId)!==revision)return;
    const values=[...(this.data[conversationId]??[])];if(!values.includes(key))values.push(key);
    const next={...this.data,[conversationId]:values};await this.save(next);this.data=next;
  });}
  clearConversation(conversationId:string): Promise<void> {
    this.epoch.set(conversationId,this.revision(conversationId)+1);
    return this.serial(async()=>{await this.load();const next={...this.data};delete next[conversationId];await this.save(next);this.data=next;});
  }
}
